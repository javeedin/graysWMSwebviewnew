-- 102_sales_lens.sql — Sales Lens: the APEX copy of every build (WMS_SI_*).
-- The page creates these tables itself on the first copy (Setup & data › Storage › Create the tables);
-- this file is the same DDL for a DBA. Generated from saleslens/sl-api.js (SL.apex.TABLES) — change both together.
-- The full results stay in C:\fusion\saleslens\data\saleslens.duckdb on the PC that builds; APEX keeps
-- the run, the top opportunities, customer scores, order-line risk, model metrics, feedback, scenarios and settings.

-- WMS_SI_RUNS
CREATE TABLE wms_si_runs (
    run_id VARCHAR2(60) PRIMARY KEY,
    run_at VARCHAR2(30),
    version VARCHAR2(60),
    pod VARCHAR2(20),
    last_month NUMBER,
    window_from NUMBER,
    window_to NUMBER,
    lines NUMBER,
    customers NUMBER,
    items NUMBER,
    opportunities NUMBER,
    lost_revenue NUMBER,
    lost_margin NUMBER,
    recoverable_margin NUMBER,
    quarantined NUMBER,
    recon_diff NUMBER,
    seconds NUMBER,
    app_user VARCHAR2(200),
    pc_name VARCHAR2(100),
    summary_json VARCHAR2(4000),
    created_date DATE DEFAULT SYSDATE);

-- WMS_SI_OPPS
CREATE TABLE wms_si_opps (
    run_id VARCHAR2(60),
    opp_id VARCHAR2(40),
    opp_rank NUMBER,
    account_number VARCHAR2(60),
    customer VARCHAR2(300),
    tier VARCHAR2(5),
    bu_id VARCHAR2(40),
    item VARCHAR2(200),
    description VARCHAR2(400),
    profit_center VARCHAR2(200),
    window_from NUMBER,
    window_to NUMBER,
    expected_qty NUMBER,
    actual_qty NUMBER,
    gap_qty NUMBER,
    drop_pct NUMBER,
    lost_revenue NUMBER,
    lost_margin NUMBER,
    recoverable_margin NUMBER,
    confidence NUMBER,
    score NUMBER,
    priority VARCHAR2(10),
    primary_cause VARCHAR2(30),
    secondary_cause VARCHAR2(30),
    evidence VARCHAR2(2000),
    action VARCHAR2(1000),
    owner VARCHAR2(100),
    salesperson VARCHAR2(200),
    due_date VARCHAR2(10),
    model_version VARCHAR2(60),
    scored_at VARCHAR2(30),
    created_date DATE DEFAULT SYSDATE,
    CONSTRAINT wms_si_opps_pk PRIMARY KEY (run_id,
    opp_id));

-- WMS_SI_FEEDBACK
CREATE TABLE wms_si_feedback (
    fb_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opp_id VARCHAR2(40),
    account_number VARCHAR2(60),
    item VARCHAR2(200),
    decision VARCHAR2(20),
    reason VARCHAR2(1000),
    outcome VARCHAR2(20),
    outcome_value NUMBER,
    note VARCHAR2(2000),
    app_user VARCHAR2(200),
    pc_name VARCHAR2(100),
    at_text VARCHAR2(30),
    created_date DATE DEFAULT SYSDATE);

-- WMS_SI_CUST_SCORES
CREATE TABLE wms_si_cust_scores (
    run_id VARCHAR2(60),
    account_number VARCHAR2(60),
    risk NUMBER,
    risk_band VARCHAR2(10),
    revenue_12 NUMBER,
    revenue_at_risk NUMBER,
    reasons VARCHAR2(2000),
    model_version VARCHAR2(60),
    created_date DATE DEFAULT SYSDATE,
    CONSTRAINT wms_si_cust_pk PRIMARY KEY (run_id,
    account_number));

-- WMS_SI_ORDER_RISK
CREATE TABLE wms_si_order_risk (
    run_id VARCHAR2(60),
    fulfill_line_id VARCHAR2(40),
    order_number VARCHAR2(60),
    account_number VARCHAR2(60),
    item VARCHAR2(200),
    promised VARCHAR2(10),
    risk NUMBER,
    main_risk VARCHAR2(20),
    value_at_risk NUMBER,
    reasons VARCHAR2(2000),
    created_date DATE DEFAULT SYSDATE,
    CONSTRAINT wms_si_risk_pk PRIMARY KEY (run_id,
    fulfill_line_id));

-- WMS_SI_SIMS
CREATE TABLE wms_si_sims (
    sim_id VARCHAR2(60) PRIMARY KEY,
    name VARCHAR2(200),
    run_at VARCHAR2(30),
    app_user VARCHAR2(200),
    delta_revenue NUMBER,
    delta_margin NUMBER,
    margin_low NUMBER,
    margin_high NUMBER,
    scenario_json VARCHAR2(4000),
    result_json VARCHAR2(4000),
    model_version VARCHAR2(60),
    created_date DATE DEFAULT SYSDATE);

-- WMS_SI_MODELS
CREATE TABLE wms_si_models (
    run_id VARCHAR2(60),
    model VARCHAR2(40),
    version VARCHAR2(60),
    method VARCHAR2(100),
    trained_at VARCHAR2(30),
    train_from NUMBER,
    train_to NUMBER,
    train_rows NUMBER,
    metrics_json VARCHAR2(2000),
    created_date DATE DEFAULT SYSDATE,
    CONSTRAINT wms_si_models_pk PRIMARY KEY (run_id,
    model));

-- WMS_SI_SETTINGS
CREATE TABLE wms_si_settings (
    setting_key VARCHAR2(80) PRIMARY KEY,
    setting_value VARCHAR2(4000),
    changed_by VARCHAR2(200),
    changed_date DATE DEFAULT SYSDATE);

CREATE INDEX wms_si_opps_acct_ix ON wms_si_opps (account_number, run_id);
CREATE INDEX wms_si_feedback_opp_ix ON wms_si_feedback (opp_id);
